/**
 * Who is calling the API.
 * It is the only place where the claims of a token are turned into an identity,
 * the rest of the code relies on the kind of principal.
 *
 * - `user`: someone signed in to Stylo.
 * - `service`: another application (the export service), which never acts on behalf of a user.
 * - `anonymous`: no valid token, or a token of an account that no longer exists.
 *
 * @typedef {{ kind: 'user', userId: string, user: import('../models/user.js') }} UserPrincipal
 * @typedef {{ kind: 'service', name: string }} ServicePrincipal
 * @typedef {{ kind: 'anonymous' }} AnonymousPrincipal
 * @typedef {UserPrincipal | ServicePrincipal | AnonymousPrincipal} Principal
 */

/** @type {AnonymousPrincipal} */
const ANONYMOUS = Object.freeze({ kind: 'anonymous' })

/**
 * @param {object | null | undefined} token decoded and verified JWT
 * @param {import('../models/user.js') | null | undefined} user account found from the token
 * @returns {Principal}
 */
function principalFromToken(token, user) {
  // tokens generated by `npm run generate-service-token`
  if (token?.admin === true) {
    return { kind: 'service', name: 'legacy' }
  }
  if (user) {
    return { kind: 'user', userId: user.id.toString(), user }
  }
  return ANONYMOUS
}

module.exports = { principalFromToken }
